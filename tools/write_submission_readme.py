lines.append("checks them against committed checksums.")
lines.append("")
lines.append("This package contains **only display items**.")
lines.append("")
lines.append(PLATFORM_STATEMENT)
lines.append("")
if not (platform.system() == "Darwin" and platform.machine() == "arm64"):
    lines.append(f"> **This package was built on {platform.system()} {platform.machine()}, not macOS "
                 "(Apple Silicon).** Minor")
    lines.append("> numerical differences from the reported values are expected, as described above.")
    lines.append("> See REPRODUCIBILITY.md, Cross-platform reproduction.")
    lines.append("")
lines.append("## Main figures")
lines.append("")
lines.append("Renamed to the manuscript's figure numbers. Source names are given so each maps")
lines.append("back to the script that produced it.")
lines.append("")
lines.append("| Packaged as | Source file in `final_plots/` |")
lines.append("|---|---|")
for packaged, source in [
    ("Fig2_genetic_data.png", "genetic_data.png"),
    ("Fig2_genetic_data.pdf", "pdf/genetic_data.pdf"),
    ("Fig3_perturbational_functional_genomics.png", "perturbational_functional_genomics_with_thde.png"),
    ("Fig3_perturbational_functional_genomics.pdf", "pdf/perturbational_functional_genomics_with_thde.pdf"),
    ("Fig4_model_analysis.png", "figure_model_analysis_composite.png"),
    ("Fig4_model_analysis.pdf", "pdf/figure_model_analysis_composite.pdf"),
    ("Fig5_trial_validation.png", "figure_trial_validation_immune_stages_R.png"),
    ("Fig5_trial_validation.pdf", "pdf/figure_trial_validation_immune_stages_R.pdf"),
    ("Fig6_prospective_temporal_holdout.png", "figure_prospective_temporal_holdout.png"),
    ("Fig6_prospective_temporal_holdout.pdf", "pdf/figure_prospective_temporal_holdout.pdf"),
    ("Fig7_specificity_control.png", "specificity_immune_vs_cardiac_faceted.png"),
    ("Fig7_specificity_control.pdf", "pdf/specificity_immune_vs_cardiac_faceted.pdf"),
    ("Fig8_stat4_vignette.png", "figure_stat4_vignette.png"),
    ("Fig8_stat4_vignette.pdf", "pdf/figure_stat4_vignette.pdf"),
]:
    sub = "main_figures/pdf" if packaged.endswith(".pdf") else "main_figures"
    # PDFs are rendered only on macOS; list only what was actually packaged.
    if not os.path.isfile(os.path.join(SUB, sub, packaged)):
        continue
    lines.append(f"| `{sub}/{packaged}` | `{source}` |")
lines.append("")
lines.append("## Headline numbers, read from the packaged data")
lines.append("")
lines.append("Two different AUCs appear in this work and they are not interchangeable:")
lines.append("")
gen = ladder["genetic only"]
full = ladder["full"]
lines.append(f"- **Cross-validated ROC-AUC, full model: {full:.4f}** "
             "(approved vs unlabeled, 5-fold × 5 seeds)")
lines.append(f"- Cross-validated ROC-AUC, genetic priors only: {gen:.4f}")
lines.append(f"- **Held-out in-trial ROC-AUC, full model: {heldout['auc_full']:.4f}** "
             f"({heldout['n_in_trial']:,} in-trial vs {heldout['n_non_target']:,} non-target genes)")
lines.append(f"- Held-out in-trial ROC-AUC, genetics only: {heldout['auc_genetics']:.4f} "
             f"(Δ {heldout['delta']:+.4f}, paired DeLong p = {heldout['delong_p']:.3f})")
lines.append("")
lines.append("The cross-validated AUC is deflated by construction — unlabeled genes are scored")
lines.append("as negatives when an unknown number are undiscovered targets — and is intended for")
lines.append("model comparison, not as an absolute performance claim.")
lines.append("")
lines.append("## Supplementary figures")
lines.append("")
lines.append("| Packaged as | Source file |")
lines.append("|---|---|")
