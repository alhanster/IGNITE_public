for figure in supplementary_figures():
    lines.append(f"| `supplementary_figures/{figure['submission_name']}` "
                 f"| `{figure['source']}` |")
    # Derives the source path as package_supplementary_figures.pdf_source() does, so it matches what was copied.
    stem = figure["submission_name"].rsplit(".", 1)[0]
    src_stem = figure["source"].rsplit("/", 1)[-1].rsplit(".", 1)[0]
    if os.path.isfile(os.path.join(SUB, "supplementary_figures", "pdf", f"{stem}.pdf")):
        lines.append(f"| `supplementary_figures/pdf/{stem}.pdf` | `pdf/{src_stem}.pdf` |")
lines.append("")
if not os.path.isdir(os.path.join(SUB, "main_figures", "pdf")):
    lines.append("> **No PDFs in this package.** They are rendered only on macOS, whose quartz")
    lines.append("> device writes them; every PNG, table and number above is unaffected.")
    lines.append("")
lines.append("> **S3** is produced by `build_leakage_controlled.py` → `fig_leakage_controlled.R`,")
lines.append("> with a paired DeLong on the shared 535-positive set (ΔAUC = +0.053, z = 3.62,")
lines.append("> p = 2.9e-4). AUCs at 24 features: 0.636 standard / 0.645 leakage-controlled.")
lines.append("> Provenance: `figure_data/PROVENANCE.md` in the code repository.")
lines.append("")
# This caveat names the held-out in-trial AUC value directly: it has no figure number, though reported above.
lines.append("> **The held-out in-trial AUC reported above is an in-trial AUC** and must never be")
lines.append("> presented as a drop from the headline cross-validated figure. Different label")
lines.append("> sets, different tasks. It is no longer a numbered supplementary figure; the ROC")
lines.append("> curves and discrimination statistics ship as Supplementary Table 7.")
lines.append("")
lines.append("> **S2 answers \"the increment is made of what?\"** -- the question the magnitude")
