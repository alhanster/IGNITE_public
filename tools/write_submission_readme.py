lines.append("> not changed, not that they re-derive. See `figure_data/PROVENANCE.md`.")
lines.append("")
# Renderer script names are omitted.
# One checksum table over every packaged file, main figures included. The sections above say
# where each file came from; this one is the integrity record. final_outputs/ is gitignored, so
# a packaged file with no row here has no recovery path at all.
lines.append("## Checksums")
lines.append("")
if os.path.isdir(os.path.join(SUB, "main_figures", "pdf")):
    lines.append("Every file in this package. `.pdf` rows change on each render -- the R PDF device")
    lines.append("stamps a wall-clock creation date -- so they record what was shipped rather than a")
    lines.append("reproduction claim; `tools/compare_submission.py` normalises them before comparing.")
else:
    lines.append("Every file in this package.")
lines.append("")
lines.append("| File | Bytes | SHA-256 (first 16) |")
lines.append("|---|---:|---|")
for sub in ("main_figures", "supplementary_figures", "supplementary_tables"):
    for name, size, digest in listing(sub):
        lines.append(f"| `{sub}/{name}` | {size:,} | `{digest[:16]}` |")
lines.append("")
lines.append("## Not included, and why")
lines.append("")
# Renderer script names are omitted.
lines.append("- **The held-out in-trial AUC figure** — not a numbered display item. Its statistics")
lines.append("  ship as the ROC and discrimination sheets of Supplementary Table 7, and in `figure_data/`.")
lines.append("- **`supplementary_data/`** — not included. Every table it used to carry is a")
lines.append("  sheet of a numbered supplementary table, sourced from `figure_data/`.")
lines.append("- Per-figure provenance and sample sizes — these live in the \"Reading the")
lines.append("  figures\" section of the repository README, not as a packaged file. Add a")
lines.append("  copy if the journal asks for per-panel counts.")
lines.append("")

