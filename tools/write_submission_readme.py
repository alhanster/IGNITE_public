with open(os.path.join(FIGDATA, "discordance_core_genes.csv"), newline="") as fh:
    _cuts = (_disc["lo_cut"], _disc["hi_cut"])
    _near = sum(1 for r in csv.DictReader(fh)
                if min(abs(float(r[c]) - k)
                       for c in ("pctile_genetics", "pctile_full") for k in _cuts) < 0.01)

