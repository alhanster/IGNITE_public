import platform
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SUB = os.path.join(ROOT, "final_outputs")
FIGDATA = os.path.join(ROOT, "figure_data")

# The platform statement is defined once, in the table packager.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from package_supplementary_tables import PLATFORM_STATEMENT  # noqa: E402


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def supplementary_figures():
    """Reuses the packager's TSV parser, so the README cannot disagree with what final-outputs copied."""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import package_supplementary_figures as psf

    rows = psf.read_manifest()
    psf.validate(rows)
    return sorted(rows, key=lambda r: r["number"])


def listing(subdir):
    """Every file under subdir, recursively, as (path relative to subdir, size, sha256).

    Recursive because each figure directory has a pdf/ subdirectory beside the PNGs; a flat
    os.listdir would hash the PNGs and silently omit the vector deliverable next to them.
    """
    d = os.path.join(SUB, subdir)
    out = []
    for dirpath, _, names in os.walk(d):
        for name in names:
            if name == ".DS_Store":       # Finder debris, not a deliverable; excluded tree-wide
                continue
            p = os.path.join(dirpath, name)
            if os.path.isfile(p):
                out.append((os.path.relpath(p, d), os.path.getsize(p), sha256(p)))
    return sorted(out)


