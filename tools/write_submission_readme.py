lines.append("> model\", never as reseed-stable. The aggregate statistics")
lines.append("> (rho = %.3f over %s genes; the driver axis; Mantel-Haenszel p = %.1e) are computed"
             % (_disc["spearman_arms"], f"{_disc['n_genes']:,}", _disc["mh_p"]))
